// Turns an analysis into a Markdown document.
//   walkthrough: standalone file; links are absolute GitHub URLs pinned to the analysed commit.
//   onboarding:  ONBOARDING.md meant to be committed at the repo root; links are relative,
//                so they resolve on whatever branch the file lives on.

const encodePath = (p) =>
  p
    .split("/")
    .map((seg) => encodeURIComponent(seg).replace(/\(/g, "%28").replace(/\)/g, "%29"))
    .join("/");

// Picks a backtick fence longer than any run inside the path.
function code(text) {
  const longest = Math.max(0, ...(String(text).match(/`+/g) ?? []).map((r) => r.length));
  const fence = "`".repeat(longest + 1);
  const pad = text.startsWith("`") || text.endsWith("`") ? " " : "";
  return `${fence}${pad}${text}${pad}${fence}`;
}

const oneLine = (s) => String(s ?? "").replace(/\s*\n+\s*/g, " ").trim();

export function buildMarkdown(analysis, { mode = "walkthrough", ref } = {}) {
  const onboarding = mode === "onboarding";
  const meta = analysis.repoMeta ?? {};
  const repoUrl = meta.htmlUrl || analysis.repoUrl;
  const sha = analysis.commitSha;
  const short = sha.slice(0, 7);
  const refName = ref || analysis.ref || meta.defaultBranch;
  const fileLink = (p) => `[${code(p)}](${onboarding ? encodePath(p) : `${repoUrl}/blob/${sha}/${encodePath(p)}`})`;
  const fileList = (files) => files.map(fileLink).join(", ");
  const date = new Date().toISOString().slice(0, 10);
  const c = analysis.classification ?? {};
  const out = [];

  out.push(onboarding ? `# Onboarding: ${meta.fullName}` : `# ${meta.fullName}: codebase walkthrough`, "");
  if (onboarding) {
    out.push(
      "> A guided tour for developers new to this repository: what it does, how it fits together, " +
        "which files to read first and what tends to trip people up.",
      ">",
      `> Generated by AI from commit \`${short}\`${refName ? ` (${refName})` : ""} on ${date}. ` +
        "Check it against the code, and regenerate it after significant changes.",
      "",
    );
  } else {
    out.push(
      `**Repository:** [${meta.fullName}](${repoUrl})  `,
      `**Commit:** [\`${short}\`](${repoUrl}/commit/${sha})${refName ? ` (${refName})` : ""}  `,
      `**Generated:** ${date} by Codebase Explainer`,
      "",
    );
  }

  const tags = [c.projectType, c.primaryLanguage, c.framework].filter((t) => t && t.toLowerCase() !== "none");
  out.push("## Overview", "");
  if (tags.length) out.push(`*${tags.join(" · ")}*`, "");
  if (c.purpose) out.push(`**${oneLine(c.purpose)}**`, "");
  if (analysis.overview) out.push(analysis.overview.trim(), "");

  out.push("## Architecture", "");
  if (analysis.architecture) out.push(analysis.architecture.trim(), "");
  if (analysis.layers?.length) {
    out.push("### Layers", "");
    for (const l of analysis.layers) {
      out.push(`- **${oneLine(l.name)}**: ${oneLine(l.description)}`);
      if (l.files?.length) out.push(`  - Files: ${fileList(l.files)}`);
    }
    out.push("");
  }
  if (analysis.nonObvious) out.push(`> **Not obvious from the file names:** ${oneLine(analysis.nonObvious)}`, "");

  if (analysis.readingOrder?.length) {
    out.push("## Read these files first", "");
    analysis.readingOrder.forEach((r, i) => out.push(`${i + 1}. ${fileLink(r.file)}: ${oneLine(r.reason)}`));
    out.push("");
  }

  if (analysis.confusionMap?.length) {
    out.push("## What will trip you up", "");
    for (const item of analysis.confusionMap) {
      out.push(`### ${oneLine(item.issue)}`, "", item.detail.trim(), "");
      if (item.files?.length) out.push(`Files: ${fileList(item.files)}`, "");
    }
  }

  if (analysis.fileSummaries?.length) {
    out.push("## Key files", "");
    for (const f of analysis.fileSummaries) {
      out.push(`### ${fileLink(f.path)}`, "", f.purpose.trim(), "");
      if (f.exports?.length) out.push(`- **Exports:** ${f.exports.map(code).join(", ")}`);
      if (f.dependsOn?.length) out.push(`- **Depends on:** ${f.dependsOn.map(code).join(", ")}`);
      if (f.exports?.length || f.dependsOn?.length) out.push("");
    }
  }

  if (analysis.suggestedQuestions?.length) {
    out.push("## Good questions to ask next", "");
    for (const q of analysis.suggestedQuestions) out.push(`- ${oneLine(q)}`);
    out.push("");
  }

  return out.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd() + "\n";
}

export function exportFilename(analysis, mode) {
  if (mode === "onboarding") return "ONBOARDING.md";
  const m = analysis.repoMeta ?? {};
  const base = `${m.owner ?? "repo"}-${m.name ?? "analysis"}-${analysis.commitSha.slice(0, 7)}-walkthrough.md`;
  return base.replace(/[^\w.-]+/g, "-");
}
